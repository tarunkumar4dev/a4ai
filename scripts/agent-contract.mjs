#!/usr/bin/env node
// Refresh the a4ai Agent API contract and regenerate its TypeScript types.
//
//   npm run agent:contract                                  # copy ../RAG-BACKEND/docs/agent_openapi_v2.json
//   npm run agent:contract -- --from C:/path/RAG-BACKEND     # a backend checkout somewhere else
//   npm run agent:contract -- --url http://localhost:8000/openapi.json   # a running backend (dev or real mode)
//   AGENT_BACKEND_DIR=C:/Users/me/Downloads/RAG-BACKEND npm run agent:contract
//
// Writes src/lib/agent/contract/agent_openapi_v2.json (the snapshot the tests read) and generates
// src/lib/agent/api.gen.ts with openapi-typescript. Never edit api.gen.ts by hand.
// The backend regenerates its JSON with `python -m agent.openapi_dump` (RAG-BACKEND); the running app's
// /openapi.json has the same paths, but the dump also lists every SSE event schema, so prefer the file.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outJson = join(root, "src/lib/agent/contract/agent_openapi_v2.json");
const outTs = join(root, "src/lib/agent/api.gen.ts");

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };

async function source() {
  const url = flag("--url");
  if (url) {
    const res = await fetch(url, { headers: { Accept: "application/json" } });
    if (!res.ok) throw new Error(`GET ${url} → HTTP ${res.status}`);
    return { text: await res.text(), from: url };
  }
  const dir = flag("--from") ?? process.env.AGENT_BACKEND_DIR ?? resolve(root, "../RAG-BACKEND");
  const file = join(dir, "docs/agent_openapi_v2.json");
  if (!existsSync(file)) {
    throw new Error(`No contract at ${file}. Pass --from <RAG-BACKEND checkout>, set AGENT_BACKEND_DIR, or use --url.`);
  }
  return { text: readFileSync(file, "utf8"), from: file };
}

const { text, from } = await source();
const spec = JSON.parse(text); // fail early on bad JSON
if (!spec.openapi || !spec.paths?.["/agent/chat"]) throw new Error("That is not the a4ai Agent OpenAPI document");
mkdirSync(dirname(outJson), { recursive: true });
writeFileSync(outJson, `${JSON.stringify(spec, null, 2)}\n`);

const bin = join(root, "node_modules/openapi-typescript/bin/cli.js");
execFileSync(process.execPath, [bin, outJson, "-o", outTs], { stdio: "inherit" });
const gen = readFileSync(outTs, "utf8");
writeFileSync(outTs, `// GENERATED by scripts/agent-contract.mjs from src/lib/agent/contract/agent_openapi_v2.json
// (RAG-BACKEND docs/agent_openapi_v2.json, ${spec.info?.title ?? "a4ai Agent"} ${spec.info?.version ?? ""}). Do not edit.
// eslint-disable
${gen}`);
console.log(`agent contract: ${Object.keys(spec.paths).length} paths, ${Object.keys(spec.components?.schemas ?? {}).length} schemas`);
console.log(`  from ${from.includes("://") ? from : "a local file"}`);
